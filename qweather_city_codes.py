def get_city_code(city_name):
    """
    根据城市名称获取和风天气城市代码

    参数:
        city_name: 中文城市名称（如"北京"）

    返回:
        城市代码（如"101010100"）或 None（如果城市未找到）
    """
    city_name = city_name.strip()
    if city_name in CITY_CODE_MAP:
        return CITY_CODE_MAP[city_name]
    else:
        return None


def get_city_name(city_code):
    """
    根据城市代码获取中文城市名称（反向查询）

    参数:
        city_code: 和风天气城市代码

    返回:
        城市名称或 None
    """
    for city_name, code in CITY_CODE_MAP.items():
        if code == city_code:
            return city_name
    return None


